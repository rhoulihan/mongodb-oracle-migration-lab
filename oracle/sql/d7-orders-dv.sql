-- D7, optimistic concurrency with ETags: the order as a duality view.
-- Run as MIG after D3's restore: it reads the restored MIG.orders collection
-- and builds two narrow tables from the region R03 orders only (to stay
-- small). Idempotent: drops and rebuilds. demos/d7-etag/agent.mjs runs it; it
-- also runs as-is in SQLcl:
--   @oracle/sql/d7-orders-dv.sql
-- Statements end with a line holding only "/", so trigger bodies can carry
-- their own semicolons.
--
-- Canonical form: an order (status) with its lines (sku, qty).
-- Projections: order_hdr (one row per order) and order_line (one row per
-- line, keyed by order and line number). Projected shape: the order document
-- (orders_dv), read and written through the MongoDB API or SQL, with an ETag
-- in _metadata that Oracle checks on every write.
--
-- No foreign keys to D5's region or device tables: D5 drops and rebuilds them
-- on every run, and a foreign key here would make that DROP fail (ORA-02449).

DROP VIEW IF EXISTS orders_dv
/
DROP TABLE IF EXISTS order_change_log PURGE
/
DROP TABLE IF EXISTS order_line PURGE
/
DROP TABLE IF EXISTS order_hdr PURGE
/
CREATE TABLE order_hdr (
  order_id      VARCHAR2(24) PRIMARY KEY,
  region_id     VARCHAR2(8)  NOT NULL,
  subscriber_id VARCHAR2(10) NOT NULL,
  status        VARCHAR2(16) NOT NULL,
  placed_at     TIMESTAMP    NOT NULL
)
/
-- Each line has its own one-column key, line_id, and the duality view maps
-- it, so every nested line in the document carries the key of the row it
-- came from. On 26ai Free a nested table's whole primary key must be mapped:
-- with PRIMARY KEY (order_id, line_no) and only line_no mapped, every read of
-- the view fails with ORA-40477 (docs/spikes/d7-etag-mongo-api.md).
-- line_no is the line's position in the source document (1, 2, ...).
CREATE TABLE order_line (
  line_id  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  order_id VARCHAR2(24) NOT NULL REFERENCES order_hdr ON DELETE CASCADE,
  line_no  NUMBER(3)    NOT NULL,
  sku      VARCHAR2(16) NOT NULL,
  kind     VARCHAR2(10) NOT NULL,
  qty      NUMBER(3)    NOT NULL,
  price    NUMBER(10,2) NOT NULL,
  UNIQUE (order_id, line_no)
)
/
INSERT INTO order_hdr (order_id, region_id, subscriber_id, status, placed_at)
SELECT o.data."_id".string(), o.data.region.string(), o.data.subscriber.id.string(),
       o.data.status.string(), o.data.placedAt.timestamp()
  FROM "orders" o
 WHERE o.data.region.string() = 'R03'
/
-- Ordered, so line_id numbers the lines the same way on every rebuild.
INSERT INTO order_line (order_id, line_no, sku, kind, qty, price)
SELECT o.data."_id".string(), l.line_no, l.sku, l.kind, l.qty, l.price
  FROM "orders" o,
       JSON_TABLE(o.data, '$.lines[*]' COLUMNS (
         line_no FOR ORDINALITY,
         sku     VARCHAR2(16) PATH '$.sku',
         kind    VARCHAR2(10) PATH '$.kind',
         qty     NUMBER       PATH '$.qty',
         price   NUMBER       PATH '$.price')) l
 WHERE o.data.region.string() = 'R03'
 ORDER BY 1, 2
/
-- The database's own record of every row an order write changes, so the demo
-- can count the updates that were applied (and show that a rejected write
-- applied none). One row per changed table row, written by the triggers below.
CREATE TABLE order_change_log (
  seq        NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  order_id   VARCHAR2(24) NOT NULL,
  table_name VARCHAR2(16) NOT NULL,
  line_no    NUMBER(3),
  change     VARCHAR2(80) NOT NULL,
  changed_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
)
/
CREATE OR REPLACE TRIGGER order_hdr_log
AFTER UPDATE ON order_hdr FOR EACH ROW
BEGIN
  INSERT INTO order_change_log (order_id, table_name, change)
  VALUES (:new.order_id, 'order_hdr', 'status ' || :old.status || ' -> ' || :new.status);
END;
/
CREATE OR REPLACE TRIGGER order_line_log
AFTER INSERT OR UPDATE OR DELETE ON order_line FOR EACH ROW
DECLARE
  what VARCHAR2(80);
BEGIN
  IF INSERTING THEN what := 'insert ' || :new.sku;
  ELSIF DELETING THEN what := 'delete ' || :old.sku;
  ELSE
    -- Name only the columns this write changed.
    IF :new.sku <> :old.sku THEN what := 'sku ' || :old.sku || ' -> ' || :new.sku; END IF;
    IF :new.qty <> :old.qty THEN what := what || CASE WHEN what IS NOT NULL THEN ', ' END || 'qty ' || :old.qty || ' -> ' || :new.qty; END IF;
    IF :new.price <> :old.price THEN what := what || CASE WHEN what IS NOT NULL THEN ', ' END || 'price ' || :old.price || ' -> ' || :new.price; END IF;
    what := NVL(what, 'no column changed');
  END IF;
  INSERT INTO order_change_log (order_id, table_name, line_no, change)
  VALUES (NVL(:new.order_id, :old.order_id), 'order_line', NVL(:new.line_no, :old.line_no), what);
END;
/
BEGIN
  DBMS_STATS.GATHER_TABLE_STATS(USER, 'ORDER_HDR');
  DBMS_STATS.GATHER_TABLE_STATS(USER, 'ORDER_LINE', cascade => TRUE);
END;
/
-- The order document. The header is updatable (status); lines can be
-- inserted, updated and deleted. Each nested line maps its key column
-- line_id (the join column order_id is not mapped a second time).
-- Every document read carries _metadata.etag, a hash of the document's
-- state; a write that sends a stale etag is rejected (ORA-42699).
CREATE JSON RELATIONAL DUALITY VIEW orders_dv AS
SELECT JSON {
  '_id'        : h.order_id,
  'region'     : h.region_id,
  'subscriber' : h.subscriber_id,
  'status'     : h.status,
  'placedAt'   : h.placed_at,
  'lines'      : [ SELECT JSON {
                     'lineId' : l.line_id,
                     'lineNo' : l.line_no,
                     'sku'    : l.sku,
                     'kind'   : l.kind,
                     'qty'    : l.qty,
                     'price'  : l.price }
                   FROM order_line l WITH INSERT UPDATE DELETE
                   WHERE l.order_id = h.order_id ] }
FROM order_hdr h WITH UPDATE
/
